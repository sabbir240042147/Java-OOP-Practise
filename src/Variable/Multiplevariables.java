package Variable;

public class Multiplevariables {
    public static void main(String[] args){
        int x=5;
        int y=6;
        int z=7;
        System.out.println(x+y+z);
        x=y=z;
        System.out.println(x+y+z);
        int p,q,r;
        p=q=r=5;
        System.out.println(p+q+r);
    }
}
